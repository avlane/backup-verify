"""Generate RESTORE VERIFYONLY scripts for review. Nothing here connects to a server."""
import os
import re

from . import __version__
from .chain import group_by_database, restore_chain
from .model import DIFF

DEFAULT_RESTORE_DIR = "D:\\RestoreTest"
DEFAULT_RESTORE_PREFIX = "verify_"

HEADER = """-- Generated by backup-verify {version} for {server} at {when} (server time).
-- REVIEW BEFORE RUNNING. RESTORE VERIFYONLY reads the backup media and checks that the
-- set is complete and readable (and, with CHECKSUM, that page checksums match).
-- It does not prove that the data can be restored; schedule real test restores as well.
"""


def quote_name(name):
    return "[%s]" % name


def quote_literal(value):
    return "N'%s'" % value


def device_clause(backup):
    return ", ".join("DISK = %s" % quote_literal(d) for d in backup.devices)


def verify_statement(backup):
    sql = "RESTORE VERIFYONLY FROM %s" % device_clause(backup)
    if backup.has_checksum:
        sql += " WITH CHECKSUM"
    return sql + ";"


def verify_statements(backups):
    """[(backup, sql)] for every backup in the restore chain."""
    return [(b, verify_statement(b)) for b in restore_chain(backups)]


def verify_script(database, backups, server, when):
    lines = [
        HEADER.format(version=__version__, server=server or "(unknown)",
                      when=when.strftime("%Y-%m-%d %H:%M")),
        "-- Database: " + quote_name(database),
        "",
    ]
    statements = verify_statements(backups)
    if not statements:
        lines.append("-- No usable full backup in the history window; nothing to verify.")
    for backup, sql in statements:
        lines.append("-- %s backup %d, finished %s" % (
            backup.type_name, backup.backup_set_id, backup.finish.strftime("%Y-%m-%d %H:%M:%S")))
        lines.append(sql)
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def safe_filename(name):
    return re.sub(r"[^A-Za-z0-9_.-]", "_", name)


def write_scripts(directory, names, backups, server, when, restore_dir=DEFAULT_RESTORE_DIR,
                  restore_prefix=DEFAULT_RESTORE_PREFIX):
    """Write one .verify.sql per database that has a usable full backup; return the paths."""
    os.makedirs(directory, exist_ok=True)
    grouped = group_by_database(backups)
    paths = []
    for name in names:
        mine = grouped.get(name.lower(), [])
        if not restore_chain(mine):
            continue
        path = os.path.join(directory, safe_filename(name) + ".verify.sql")
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(verify_script(name, mine, server, when))
        paths.append(path)
        if restore_chain(mine)[0].files:
            path = os.path.join(directory, safe_filename(name) + ".test-restore.sql")
            with open(path, "w", encoding="utf-8", newline="\n") as fh:
                fh.write(restore_test_script(name, mine, server, when, restore_dir, restore_prefix))
            paths.append(path)
    return paths


def move_clauses(full, target, restore_dir):
    """MOVE clauses that put every file of the test copy under restore_dir."""
    sep = "" if restore_dir.endswith(("\\", "/")) else "\\"
    clauses, seen_data = [], False
    for number, f in enumerate(full.files, 1):
        if f.file_type == "L":
            ext = ".ldf"
        else:
            ext = ".ndf" if seen_data else ".mdf"
            seen_data = True
        path = "%s%s%s_%d%s" % (restore_dir, sep, safe_filename(target), number, ext)
        clauses.append("MOVE %s TO %s" % (quote_literal(f.logical_name), quote_literal(path)))
    return clauses


def restore_test_script(database, backups, server, when, restore_dir=DEFAULT_RESTORE_DIR,
                        prefix=DEFAULT_RESTORE_PREFIX):
    """A script that restores the latest chain as a differently named database and runs CHECKDB."""
    if not prefix:
        raise ValueError("the restore prefix must not be empty: a test restore must never "
                         "target the source database")
    target = prefix + database
    lines = [
        HEADER.format(version=__version__, server=server or "(unknown)",
                      when=when.strftime("%Y-%m-%d %H:%M")),
        "-- Test restore of %s as %s" % (quote_name(database), quote_name(target)),
        "-- All files are moved under %s. The script fails if %s already exists." % (
            restore_dir, quote_name(target)),
        "",
    ]
    chain = restore_chain(backups)
    if not chain:
        lines.append("-- No usable full backup in the history window; nothing to restore.")
        return "\n".join(lines) + "\n"
    full = chain[0]
    if not full.files:
        lines.append("-- msdb has no file list for full backup %d, so MOVE clauses cannot be built." %
                     full.backup_set_id)
        return "\n".join(lines) + "\n"
    options = move_clauses(full, target, restore_dir) + ["NORECOVERY", "STATS = 10"]
    lines.append("-- full backup %d, finished %s" % (full.backup_set_id, full.finish.strftime("%Y-%m-%d %H:%M:%S")))
    lines.append("RESTORE DATABASE %s" % quote_name(target))
    lines.append("  FROM %s" % device_clause(full))
    lines.append("  WITH " + ",\n       ".join(options) + ";")
    for backup in chain[1:]:
        verb = "DATABASE" if backup.type == DIFF else "LOG"
        lines.append("-- %s backup %d, finished %s" % (
            backup.type_name, backup.backup_set_id, backup.finish.strftime("%Y-%m-%d %H:%M:%S")))
        lines.append("RESTORE %s %s FROM %s WITH NORECOVERY;" % (verb, quote_name(target), device_clause(backup)))
    lines.append("RESTORE DATABASE %s WITH RECOVERY;" % quote_name(target))
    lines.append("")
    lines.append("DBCC CHECKDB (%s) WITH NO_INFOMSGS, ALL_ERRORMSGS;" % quote_literal(target))
    lines.append("")
    lines.append("-- DROP DATABASE %s;  -- run this when you are done with the test restore" % quote_name(target))
    return "\n".join(lines) + "\n"
